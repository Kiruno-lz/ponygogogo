const DICTS: Record<Lang, Dict> = { zh, en }

export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const raw = DICTS[lang][key]
  if (raw === undefined) throw new Error(`MISSING_TRANSLATION:${lang}:${key}`)
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''))
}

export function localized(key: string, vars?: Record<string, string | number>): { zh: string; en: string } {
  return { zh: t('zh', key, vars), en: t('en', key, vars) }
}

export function ponyName(ponyId: number, lang: Lang): string {
  return t(lang, `pony.${ponyId}.name`)
}
