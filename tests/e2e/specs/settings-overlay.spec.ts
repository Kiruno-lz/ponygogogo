import { expect, test } from '@playwright/test'
import { enterHome, open } from '../helpers.ts'

test('settings floats over the unchanged home and dismisses at the edge with focus restored', async ({ page }) => {
  await open(page)
  await enterHome(page)
  const opener = page.getByRole('button', { name: /游戏设置|SETTINGS/ }).first()
  const stage = page.getByTestId('stage')
  const before = await stage.boundingBox()
  await opener.click()
  const modal = page.getByTestId('screen-settings')
  await expect(modal).toBeVisible()
  await expect(page.getByTestId('screen-home')).toBeVisible()
  expect(await stage.boundingBox()).toEqual(before)
  await expect(modal.getByRole('button', { name: /^返回$|^Back$/ })).toHaveCount(0)
  await page.getByTestId('vol-master').fill('40')
  await expect(modal).toBeVisible()
  await page.getByRole('button', { name: 'English', exact: true }).click()
  await expect(modal).toHaveAttribute('aria-label', 'Settings')
  await page.screenshot({ path: 'tests/e2e/screenshots/settings-overlay.png' })
  await page.mouse.click(before!.x + 10, before!.y + 10)
  await expect(modal).toBeHidden()
  await expect(opener).toBeFocused()
  await opener.click()
  await expect(page.getByTestId('vol-master')).toHaveValue('40')
  await page.keyboard.press('Escape')
  await expect(modal).toBeHidden()
  await expect(opener).toBeFocused()
})
